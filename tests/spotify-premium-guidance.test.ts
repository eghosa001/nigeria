import assert from "node:assert/strict";
import test from "node:test";
import { getDetailedServiceGuidance, hasExplicitServiceGuidance } from "../lib/service-guidance";

const guidance = getDetailedServiceGuidance({ slug: "spotify-premium-nigeria" } as Parameters<typeof getDetailedServiceGuidance>[0]);

test("Spotify Premium guide uses the official online subscription and renewal process", () => {
  assert.equal(hasExplicitServiceGuidance("spotify-premium-nigeria"), true);
  assert.match(guidance.route.startDetail, /spotify\.com\/ng\/premium/);
  assert.match(guidance.route.startDetail, /₦1,600/);
  assert.match(guidance.route.physicalTitle, /online/);
  assert.doesNotMatch(JSON.stringify(guidance), /quote the reference generated by this application|responsible agency|passport appointment/i);
});

test("Spotify cancellation advice distinguishes direct plans, free trials and partner billing", () => {
  const details = guidance.aftercare.map(item => item.detail).join(" ");
  assert.match(details, /next billing date/);
  assert.match(details, /zero-priced free trial/);
  assert.match(details, /partner/);
  assert.match(guidance.route.fallbackDetail, /support\.spotify\.com/);
});
