import test from "node:test";
import assert from "node:assert/strict";
import { getPublicService } from "../lib/data";
import { getRequirementDetails } from "../lib/requirement-details";
import { getStepDetails } from "../lib/step-details";
import { getDetailedServiceGuidance } from "../lib/service-guidance";
import { getMovieEditorialProfile } from "../lib/movie-editorial-profile-registry";
import { getVisibleMovieEditorial } from "../lib/movie-editorial-presentation";

test("service steps and requirements are not padded by fuzzy source-free associations", () => {
  for (const slug of ["nin-enrolment", "nin-sim-linkage", "passport-renewal"]) {
    const service = getPublicService(slug);
    assert.ok(service, slug);
    const requirements = getRequirementDetails(service);
    const steps = getStepDetails(service);
    assert.deepEqual(requirements.map(r => r.item), service.requirements, slug);
    assert.deepEqual(steps.map(s => s.instruction), service.steps, slug);
    assert.ok(requirements.every(r => !r.whenUsed), slug);
    assert.ok(steps.every(s => s.prepare.length === 0), slug);
  }
});

test("unspecified document formats stay unspecified", () => {
  const service = getPublicService("nin-sim-linkage");
  assert.ok(service);
  const details = getRequirementDetails(service);
  assert.ok(details.length > 0);
  assert.ok(details.every(r => !r.format || /explicitly calls/.test(r.format)));
});

test("a free, reference-free service is not given a made-up payment receipt", () => {
  const original = getPublicService("nin-sim-linkage");
  assert.ok(original);
  const service = {
    ...original, slug: "sample-reference-free-process", agencySlug: "unknown",
    feeLabel: "FREE", steps: ["Use the provider's official information service.", "Review the status shown."],
  };
  const guidance = getDetailedServiceGuidance(service);
  assert.doesNotMatch(guidance.aftercare.map(item => item.detail).join(" "), /payment receipt|payment reference|reference generated by this application/i);
  assert.match(guidance.aftercare[0].detail, /if the responsible organisation provides one/i);
});

test("Abe Odale remains sourced but omits repeated watch-link uncertainty", () => {
  const dossier = getMovieEditorialProfile("abe-odale-2026");
  assert.ok(dossier);
  const visible = getVisibleMovieEditorial("abe-odale-2026", dossier);
  assert.equal(visible.sections.length, dossier.sections.length - 2);
  assert.equal(visible.questions.length, dossier.questions.length - 2);
  assert.ok(visible.questions.some(q => /watch/i.test(q.question) && /not.*verif/i.test(q.answer)));
  const another = getMovieEditorialProfile("what-love-is");
  assert.ok(another);
  assert.equal(getVisibleMovieEditorial("what-love-is", another).sections.length, another.sections.length);
});
