import assert from "node:assert/strict";
import test from "node:test";
import { getPublicService } from "../lib/data";
import { getDetailedServiceGuidance, hasExplicitServiceGuidance } from "../lib/service-guidance";
import { getOfficialServiceLinks } from "../lib/official-links";

const service = getPublicService("western-union-track-transfer-nigeria");
assert.ok(service, "Western Union MTCN guide must exist");

test("Western Union MTCN guide links directly to the legitimate provider's action and instructions", () => {
  const links = getOfficialServiceLinks(service);
  assert.equal(links.guidanceUrl, "https://www.westernunion.com/ng/en/receive-money.html");
  assert.equal(links.actionUrl, "https://www.westernunion.com/global-service/track-transfer");
  assert.match(links.guidanceLabel ?? "", /official instructions/);
  assert.match(links.actionLabel ?? "", /official service portal/);
  assert.notEqual(links.guidanceUrl, "https://www.westernunion.com/ng/en/legal/terms-conditions.html");
});

test("MTCN guide separates free online tracking from cash pickup and bank credit", () => {
  assert.equal(hasExplicitServiceGuidance(service.slug), true);
  const { route, aftercare } = getDetailedServiceGuidance(service);
  assert.match(route.startDetail, /10-digit|ten-digit/);
  assert.match(route.startDetail, /westernunion.com\/global-service\/track-transfer/);
  assert.match(route.physicalDetail, /No agent visit is needed/);
  assert.match(route.physicalDetail, /bank-account payout/);
  assert.match(route.fallbackDetail, /0700-34778-2668228/);
  assert.match(route.fallbackDetail, /westernunion.com\/ng\/en\/contact-us/);
  assert.match(aftercare.map((c) => c.detail).join(" "), /bank.*statement/i);
  assert.doesNotMatch(JSON.stringify({ route, aftercare }), /quote the reference generated by this application|new application reference to follow up|mandatory registration appointment/i);
});
