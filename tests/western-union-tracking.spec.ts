import { test, expect } from "@playwright/test";

test("Western Union transfer tracking shows the direct MTCN action and truthful support process", async ({ page }) => {
  const response = await page.goto("/services/western-union-track-transfer-nigeria");
  expect(response?.status()).toBe(200);
  await expect(page.getByRole("heading", { name: /Western Union Tracking in Nigeria/i }).first()).toBeVisible();
  await expect(page.locator('a[href="https://www.westernunion.com/global-service/track-transfer"]').first()).toBeVisible();
  await expect(page.locator('a[href="https://www.westernunion.com/ng/en/receive-money.html"]').first()).toBeVisible();
  await expect(page.locator("body")).toContainText("0700-34778-2668228");
  await expect(page.locator("body")).not.toContainText("quote the reference generated by this application");
});
